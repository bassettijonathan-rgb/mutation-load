// Compiles src/wasm/kernel.c to WebAssembly and writes it, base64-encoded,
// to src/sim/kernel-wasm.js. Needs clang with the wasm32 target (clang 18 was
// used). The output is committed, so the page build and CI do not need clang;
// test/unit/kernel.test.js checks that it gives exactly the JavaScript
// results.
//
//   node tools/build-wasm.mjs

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdtempSync, rmSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { tmpdir } from 'node:os';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = mkdtempSync(join(tmpdir(), 'kernel-'));
const out = join(dir, 'kernel.wasm');
try {
  execFileSync('clang', [
    '--target=wasm32',
    '-O3',
    '-ffp-contract=off',
    '-fno-builtin',
    '-nostdlib',
    '-Wl,--no-entry',
    '-Wl,--export=setup',
    '-Wl,--export=breed',
    '-Wl,--export=__heap_base',
    '-Wl,--import-memory',
    '-Wl,--allow-undefined',
    '-o',
    out,
    join(root, 'src/wasm/kernel.c'),
  ]);
  const bytes = readFileSync(out);
  const version = execFileSync('clang', ['--version']).toString().split('\n')[0];
  const js = `// Generated by tools/build-wasm.mjs from src/wasm/kernel.c (${version}).
// Do not edit by hand.
export const KERNEL_WASM = '${bytes.toString('base64')}';
`;
  writeFileSync(join(root, 'src/sim/kernel-wasm.js'), js);
  console.log(`src/sim/kernel-wasm.js: ${bytes.length} bytes of WebAssembly`);
} finally {
  rmSync(dir, { recursive: true, force: true });
}
